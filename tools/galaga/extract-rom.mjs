/**
 * Writes the data tables of the Galaga port (games/galaga/src/rom.c and art.c) from the web
 * version in insert-coin, which extracted them from the original ROMs and PROMs: the tables of the
 * main program, the flight programs of the second processor, the sound program's data, the
 * waveforms of the sound chip, the colours, the sprites and the characters. The 05xx starfield is
 * added too: the 256 stars its shift register draws, found once here instead of at every start.
 *
 *   node tools/galaga/extract-rom.mjs INSERT_COIN_DIR
 *
 * INSERT_COIN_DIR is a checkout of github.com/DarkHelmet67/insert-coin with its packages installed
 * (pnpm install). The generated files are formatted with clang-format and must not be edited.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const [insertCoin] = process.argv.slice(2);
if (!insertCoin) {
  console.error('usage: extract-rom.mjs INSERT_COIN_DIR');
  process.exit(1);
}
const gameDir = resolve(insertCoin, 'games/galaga/src');
const { createServer } = await import(
  pathToFileURL(resolve(insertCoin, 'node_modules/vite/dist/node/index.js')).href
);
const vite = await createServer({
  root: resolve(insertCoin),
  logLevel: 'error',
  server: { middlewareMode: true, hmr: false },
  appType: 'custom',
});
const load = (name) => vite.ssrLoadModule(join(gameDir, name));
const mainRom = await load('rom/main-rom.ts');
const { FLIGHT_ROM } = await load('rom/flight-rom.ts');
const { SOUND_DATA, SOUND_DATA_ADDRESS, WAVEFORM_PROM } = await load('rom/sound-rom.ts');
const { PALETTE_PROM, CHAR_LOOKUP_PROM, SPRITE_LOOKUP_PROM } = await load('art/color-proms.ts');
const { nextLfsr } = await load('stars.ts');
const art = await Promise.all(
  ['00', '08', '10', '18', '20', '28', '30', '38', '40', '48', '50', '58', '60', '68', '70', '78'].map(
    (n) => load(`art/sprites-${n}.ts`).then((m) => m[`sprites${n}`]),
  ),
);
const chars = await Promise.all(
  ['00', '20', '40', '60'].map((n) => load(`art/chars-${n}.ts`).then((m) => m[`chars${n}`])),
);
const commit = execFileSync('git', ['-C', insertCoin, 'rev-parse', '--short', 'HEAD'])
  .toString()
  .trim();

const hex2 = (n) => `0x${n.toString(16).padStart(2, '0')}`;
const hexN = (n, digits) => `0x${n.toString(16).padStart(digits, '0')}`;

/** A C table of bytes. */
const byteTable = (name, bytes) =>
  `GAME_PRIVATE const uint8_t ${name}[${bytes.length}] = {${bytes.map(hex2).join(', ')}};\n`;

const banner = (what) =>
  `/* SPDX-License-Identifier: GPL-3.0-only */\n` +
  `/*\n * Generated by tools/galaga/extract-rom.mjs from insert-coin ${commit}: do not edit.\n` +
  ` * ${what}\n */\n`;

// ---- rom.c: the tables

/** The tables of the main ROM, with the C name of each. */
const MAIN_TABLES = [
  'SCORE_STEPS',
  'RED_BOMBER_TIMERS',
  'YELLOW_BOMBER_TIMERS',
  'BOMB_ENABLE_TABLE',
  'CLONE_BONUS',
  'BOSS_SCORES',
  'ESCORTS',
  'BREATHING_BITMAPS',
  'BEAM_TILES',
  'COMBAT_STAGE_INDEX',
  'CHALLENGE_STAGE_INDEX',
  'COMBAT_STAGES',
  'CHALLENGE_STAGES',
  'WAVE_OBJECTS',
  'CHALLENGE_BONUS',
  'BOMBER_BITS',
  'CHALLENGE_LOOKS',
  'ENTRY_PROGRAMS',
  'ENTRY_STARTS',
  'STAGE_PARAMETERS',
];

/** The flight ROM as one run of bytes from its first area; the gaps read $FF. */
const flightFirst = Math.min(...FLIGHT_ROM.map((a) => a.address));
const flightEnd = Math.max(...FLIGHT_ROM.map((a) => a.address + a.bytes.length));
const flight = Array.from({ length: flightEnd - flightFirst }, () => 0xff);
FLIGHT_ROM.forEach((area) =>
  area.bytes.forEach((byte, i) => {
    flight[area.address - flightFirst + i] = byte;
  }),
);

/** The 05xx stars: register step, set and colour bits (stars.ts, findStars). */
const STAR_SEED = 0x7fff;
const STAR_PERIOD = 65535;
const stars = [];
let lfsr = STAR_SEED;
for (let step = 0; step < STAR_PERIOD; step++) {
  if ((lfsr & 0xfa14) === 0x7800) {
    const set = (((lfsr >> 10) & 1) << 1) | ((lfsr >> 8) & 1);
    const color = ~(((lfsr >> 5) & 0x07) | ((lfsr << 3) & 0x18) | ((lfsr << 2) & 0x20)) & 0x3f;
    stars.push({ step, set, color });
  }
  lfsr = nextLfsr(lfsr);
}

const romHeader =
  banner('The tables of the original ROMs, as the web version extracted them.') +
  `#ifndef GALAGA_ROM_H\n#define GALAGA_ROM_H\n\n#include <stdint.h>\n\n#include "cartridge/private.h"\n\n` +
  MAIN_TABLES.map(
    (name) =>
      `/** \`${name}\` of the main ROM (rom/main-rom.ts). */\n#define ${name}_SIZE ${mainRom[name].length}u\nGAME_EXTERN const uint8_t ${name}[${name}_SIZE];\n`,
  ).join('\n') +
  `\n/** The data areas of the second processor's ROM, from address FLIGHT_ROM_FIRST; gaps read $FF. */\n` +
  `#define FLIGHT_ROM_FIRST ${hexN(flightFirst, 4)}u\n#define FLIGHT_ROM_SIZE ${flight.length}u\n` +
  `GAME_EXTERN const uint8_t FLIGHT_ROM[FLIGHT_ROM_SIZE];\n\n` +
  `/** The data of the sound program, from address SOUND_DATA_ADDRESS (rom/sound-rom.ts). */\n` +
  `#define SOUND_DATA_ADDRESS ${hexN(SOUND_DATA_ADDRESS, 4)}u\n#define SOUND_DATA_SIZE ${SOUND_DATA.length}u\n` +
  `GAME_EXTERN const uint8_t SOUND_DATA[SOUND_DATA_SIZE];\n\n` +
  `/** The waveform PROM of the sound chip: 8 waveforms of 32 samples, one per byte. */\n` +
  `#define WAVEFORM_PROM_SIZE ${WAVEFORM_PROM.length}u\nGAME_EXTERN const uint8_t WAVEFORM_PROM[WAVEFORM_PROM_SIZE];\n\n` +
  `/** The colour PROMs: 32 colours as BBGGGRRR, and 4 entries per character and sprite palette. */\n` +
  `#define PALETTE_PROM_SIZE ${PALETTE_PROM.length}u\nGAME_EXTERN const uint8_t PALETTE_PROM[PALETTE_PROM_SIZE];\n` +
  `#define CHAR_LOOKUP_PROM_SIZE ${CHAR_LOOKUP_PROM.length}u\nGAME_EXTERN const uint8_t CHAR_LOOKUP_PROM[CHAR_LOOKUP_PROM_SIZE];\n` +
  `#define SPRITE_LOOKUP_PROM_SIZE ${SPRITE_LOOKUP_PROM.length}u\nGAME_EXTERN const uint8_t SPRITE_LOOKUP_PROM[SPRITE_LOOKUP_PROM_SIZE];\n\n` +
  `/** One star of the 05xx chip: the shift register step that draws it, its set (0-3), its colour (BBGGRR). */\n` +
  `typedef struct {\n    uint16_t step;\n    uint8_t set;\n    uint8_t color;\n} StarSeed;\n\n` +
  `/** The stars the chip can draw, in the order of their steps. */\n#define STAR_COUNT ${stars.length}u\nGAME_EXTERN const StarSeed STAR_SEEDS[STAR_COUNT];\n\n#endif\n`;

const romSource =
  banner('The tables of the original ROMs, as the web version extracted them.') +
  `#include "rom.h"\n\n` +
  MAIN_TABLES.map((name) => byteTable(name, mainRom[name])).join('\n') +
  '\n' +
  byteTable('FLIGHT_ROM', flight) +
  '\n' +
  byteTable('SOUND_DATA', SOUND_DATA) +
  '\n' +
  byteTable('WAVEFORM_PROM', WAVEFORM_PROM) +
  '\n' +
  byteTable('PALETTE_PROM', PALETTE_PROM) +
  byteTable('CHAR_LOOKUP_PROM', CHAR_LOOKUP_PROM) +
  byteTable('SPRITE_LOOKUP_PROM', SPRITE_LOOKUP_PROM) +
  '\n' +
  `GAME_PRIVATE const StarSeed STAR_SEEDS[STAR_COUNT] = {\n` +
  stars.map((s) => `{${s.step}u, ${s.set}u, ${hex2(s.color)}u},`).join('\n') +
  '\n};\n';

// ---- art.c: the tiles, two bits a pixel

const sprites = art.flat();
const charRows = chars.flat();

/** A row of art as a number: pixel x in bits 2x and 2x + 1, so the leftmost is the lowest. */
const packRow = (row) =>
  [...row].reduce((value, c, x) => value + (c === '.' ? 0 : Number(c)) * 4 ** x, 0);

const artHeader =
  banner('The sprites and characters of the original ROMs, two bits a pixel.') +
  `#ifndef GALAGA_ART_H\n#define GALAGA_ART_H\n\n#include <stdint.h>\n\n#include "cartridge/private.h"\n\n` +
  `/** Sprites: 128 tiles of 16 x 16 pixels; pixel x of a row is bits 2x and 2x + 1 (0 is see-through). */\n` +
  `#define SPRITE_TILES ${sprites.length}u\n#define SPRITE_SIZE 16\n` +
  `GAME_EXTERN const uint32_t SPRITE_ART[SPRITE_TILES][SPRITE_SIZE];\n\n` +
  `/** Characters: 128 tiles of 8 x 8 pixels, packed the same way. */\n` +
  `#define CHAR_TILES ${charRows.length}u\n#define CHAR_SIZE 8\n` +
  `GAME_EXTERN const uint16_t CHAR_ART[CHAR_TILES][CHAR_SIZE];\n\n#endif\n`;

const artSource =
  banner('The sprites and characters of the original ROMs, two bits a pixel.') +
  `#include "art.h"\n\n` +
  `GAME_PRIVATE const uint32_t SPRITE_ART[SPRITE_TILES][SPRITE_SIZE] = {\n` +
  sprites
    .map((tile, code) => `/* ${hex2(code)} */ {${tile.map((r) => `${hexN(packRow(r), 8)}u`).join(', ')}},`)
    .join('\n') +
  '\n};\n\n' +
  `GAME_PRIVATE const uint16_t CHAR_ART[CHAR_TILES][CHAR_SIZE] = {\n` +
  charRows
    .map((tile, code) => `/* ${hex2(code)} */ {${tile.map((r) => `${hexN(packRow(r), 4)}u`).join(', ')}},`)
    .join('\n') +
  '\n};\n';

const out = 'games/galaga/src';
const files = {
  'rom.h': romHeader,
  'rom.c': romSource,
  'art.h': artHeader,
  'art.c': artSource,
};
Object.entries(files).forEach(([name, text]) => writeFileSync(join(out, name), text));
execFileSync('clang-format', ['-i', ...Object.keys(files).map((name) => join(out, name))]);
console.log(
  `${Object.keys(files).join(', ')}: ${sprites.length} sprites, ${charRows.length} characters, ${stars.length} stars, flight ROM ${flight.length} bytes`,
);
await vite.close();
